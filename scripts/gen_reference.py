#!/usr/bin/env python3
"""Generate docs/reference.md from the live CLI click tree and the MCP server's tool list.

Usage:
    python scripts/gen_reference.py           # rewrite docs/reference.md
    python scripts/gen_reference.py --check   # exit 1 if the committed file is stale

The output is deterministic (sorted, no timestamps, no absolute paths) so a byte comparison
against the committed file is a valid drift check (tests/test_docs_consistency.py).
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path
from typing import Any

import click

from strata_lookml.cli.main import strata_cli
from strata_lookml.ir.types import IRGraph
from strata_lookml.mcp.server import create_server

REPO_ROOT = Path(__file__).resolve().parents[1]
REFERENCE = REPO_ROOT / "docs" / "reference.md"

_HEADER = """\
# Strata Reference

> Generated by `scripts/gen_reference.py` from the real CLI and MCP server. Do not edit by hand:
> change the help string or tool docstring, then run `python scripts/gen_reference.py`.
> `tests/test_docs_consistency.py` fails when this file is stale.
"""


def _first_paragraph(text: str | None) -> str:
    if not text:
        return ""
    para = click.unstyle(text).strip().split("\n\n", 1)[0]
    return " ".join(para.split())


def _portable(value: Any) -> str:
    """Render a default so it never embeds the generating machine's home or working directory."""
    text = str(value)
    home = str(Path.home())
    if home and home != "/":
        text = text.replace(home, "~")
    return text.replace(str(Path.cwd()), ".")


def _option_line(param: click.Parameter, ctx: click.Context) -> str:
    if isinstance(param, click.Argument):
        label = param.make_metavar(ctx)
        parts = [f"`{label}`", "argument", "required" if param.required else "optional"]
    else:
        label = " / ".join(param.opts + param.secondary_opts)
        if not getattr(param, "is_flag", False):
            label += f" {param.make_metavar(ctx)}"
        parts = [f"`{label}`"]
        if param.required:
            parts.append("required")
        if getattr(param, "is_flag", False):
            parts.append("flag")
        if param.envvar:
            envs = [param.envvar] if isinstance(param.envvar, str) else list(param.envvar)
            parts.append("env " + ", ".join(f"`{e}`" for e in envs))
        default = param.default
        # click 8.3 uses an enum sentinel for "no default"; flags carry a bool default we omit.
        has_default = default is not None and type(default).__name__ != "Sentinel"
        if has_default and not getattr(param, "is_flag", False) and not callable(default):
            parts.append(f"default `{_portable(default)}`")
        helptext = getattr(param, "help", None)
        if helptext:
            parts.append(_first_paragraph(helptext))
    return "- " + " — ".join(parts)


def _walk(cmd: click.Command, path: list[str]) -> list[tuple[list[str], click.Command]]:
    out = [(path, cmd)]
    if isinstance(cmd, click.Group):
        ctx = click.Context(cmd, info_name=path[-1])
        for name in sorted(cmd.list_commands(ctx)):
            sub = cmd.get_command(ctx, name)
            if sub is None or sub.hidden:
                continue
            out.extend(_walk(sub, [*path, name]))
    return out


def visible_commands() -> list[tuple[list[str], click.Command]]:
    """Every non-hidden command and subcommand, depth-first and sorted, excluding the root."""
    return _walk(strata_cli, ["strata"])[1:]


def mcp_tools() -> list[Any]:
    server = create_server(IRGraph(repo_path="repo", built_at="reference"))
    return sorted(asyncio.run(server.list_tools()), key=lambda t: t.name)


def _is_read_only(tool: Any) -> bool:
    return bool(tool.annotations and tool.annotations.read_only_hint)


def counts() -> dict[str, int]:
    tools = mcp_tools()
    ro = sum(_is_read_only(t) for t in tools)
    return {"tools": len(tools), "read_only": ro, "commands": len(visible_commands())}


def _schema_type(schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return " | ".join(repr(v) for v in schema["enum"])
    if "type" in schema:
        t = schema["type"]
        if t == "array" and isinstance(schema.get("items"), dict):
            return f"array of {_schema_type(schema['items'])}"
        return str(t)
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(_schema_type(s) for s in schema[key])
    return "any"


def _render_cli() -> list[str]:
    lines = ["## CLI", ""]
    for path, cmd in visible_commands():
        ctx = click.Context(cmd, info_name=path[-1])
        usage = " ".join(path) + " " + " ".join(cmd.collect_usage_pieces(ctx))
        lines += [f"### `{' '.join(path)}`", "", f"`{usage.strip()}`", ""]
        summary = _first_paragraph(cmd.help)
        if summary:
            lines += [summary, ""]
        params = [
            p
            for p in cmd.get_params(ctx)
            if p.opts != ["--help"] and not getattr(p, "hidden", False)
        ]
        if params:
            lines += [_option_line(p, ctx) for p in params] + [""]
    return lines


def _render_mcp() -> list[str]:
    tools = mcp_tools()
    c = counts()
    lines = [
        "## MCP tools",
        "",
        f"{c['tools']} tools, {c['read_only']} read-only.",
        "",
    ]
    for tool in tools:
        lines += [f"### `{tool.name}`", ""]
        if tool.title:
            lines += [f"**{tool.title}**" + (" (read-only)" if _is_read_only(tool) else ""), ""]
        if tool.description:
            lines += [_first_paragraph(tool.description), ""]
        props = (tool.input_schema or {}).get("properties", {})
        required = set((tool.input_schema or {}).get("required", []))
        if props:
            lines.append("Parameters:")
            for name, schema in props.items():
                desc = _first_paragraph(schema.get("description"))
                bits = [
                    f"`{name}`",
                    _schema_type(schema),
                    "required" if name in required else "optional",
                ]
                if "default" in schema:
                    bits.append(f"default `{schema['default']}`")
                if desc:
                    bits.append(desc)
                lines.append("- " + " — ".join(bits))
            lines.append("")
        else:
            lines += ["Parameters: none.", ""]
        if tool.annotations:
            ann = tool.annotations.model_dump(exclude_none=True)
            lines += ["Annotations: " + ", ".join(f"`{k}={v}`" for k, v in sorted(ann.items())), ""]
    return lines


def render() -> str:
    c = counts()
    lines = [
        _HEADER,
        f"At a glance: {c['commands']} CLI commands (incl. subcommands), {c['tools']} MCP tools "
        f"({c['read_only']} read-only).",
        "",
        *_render_cli(),
        *_render_mcp(),
    ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/reference.md is stale")
    args = parser.parse_args(argv)
    generated = render()
    if args.check:
        current = REFERENCE.read_text(encoding="utf-8") if REFERENCE.exists() else ""
        if current != generated:
            print(
                "docs/reference.md is stale: run `python scripts/gen_reference.py`",
                file=sys.stderr,
            )
            return 1
        return 0
    REFERENCE.write_text(generated, encoding="utf-8")
    print(f"wrote {REFERENCE.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
